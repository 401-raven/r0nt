#!/usr/bin/env python3
"""Generate docs/CODEMAP.md: public API of src/r0nt, so a model need not read all code."""
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "r0nt"
OUT = ROOT / "docs" / "CODEMAP.md"


def sig(node):
    try:
        args = ast.unparse(node.args)
    except Exception:
        args = "..."
    ret = f" -> {ast.unparse(node.returns)}" if node.returns else ""
    return f"({args}){ret}"


def first_line(node):
    doc = ast.get_docstring(node)
    return doc.strip().splitlines()[0] if doc else ""


def describe(path):
    tree = ast.parse(path.read_text(encoding="utf-8"))
    rel = path.relative_to(SRC).as_posix()
    in_tui = rel.startswith("tui/")
    lines = [f"### `{rel}`"]
    mod_doc = first_line(tree)
    if mod_doc:
        lines.append(mod_doc)
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and not node.name.startswith("_"):
            d = first_line(node)
            lines.append(f"- `def {node.name}{sig(node)}`" + (f": {d}" if d else ""))
        elif isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            d = first_line(node)
            lines.append(f"- `class {node.name}`" + (f": {d}" if d else ""))
            if not in_tui:
                for m in node.body:
                    if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef)) and not m.name.startswith("_"):
                        lines.append(f"  - `{m.name}{sig(m)}`")
    return "\n".join(lines)


def main():
    if not SRC.exists():
        print(f"error: {SRC} not found", file=sys.stderr)
        return 1
    parts = ["# Code map (generated by scripts/gen_codemap.py, do not edit by hand)", ""]
    for p in sorted(SRC.rglob("*.py")):
        if p.name == "__init__.py" and p.stat().st_size == 0:
            continue
        parts.append(describe(p))
        parts.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
